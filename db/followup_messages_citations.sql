-- 本机 locale 是 cp936,不钉这一行中文会在客户端侧被重编码(本仓记过这条)。
SET NAMES utf8mb4;

-- ⚠️ **这份文件刻意不带章号**(不叫 `ch11.sql`):它不是一章的产物,是一次
--    缺陷修复。占一个章号会让后来人以为有一章 ch11 存在,而按章号去排升级顺序。
--
-- ⚠️ **走法(本仓硬约束:「`scripts/init_db.py` 永不加列」)**
--    `create_all` 对**已存在**的表是**空操作** —— 它不比对形状、也不报错。
--    所以:
--      · **已存在的库**(包括本机这个、以及任何 clone 出来已跑过 init_db 的):
--        `init_db.py` **不会**加这一列 ⇒ **必须手动跑这份文件**。
--      · **全新空库**:`scripts/init_db.py` 的 `create_all` 会**连这一列一起**
--        把 `messages` 建出来(ORM 侧有它)⇒ 这份文件在那种库上是**空操作不需要**,
--        跑了会在这条 ALTER 上报 **1060**(列已存在)。**这是刻意的已知取舍**,
--        与 `db/ch08.sql` 的 `tool_audit_logs`、`db/ch09.sql` 的两列同款。
--    ⇒ 一句话:**升级老库跑它,新建库不跑它。**
--
-- ⚠️ **本文件刻意不幂等**:不带任何幂等守卫(`IF NOT EXISTS` 之类),与
--    db/ch03 / ch04 / ch06 / ch07 / ch08 / ch09 / ch10 同规矩。重复执行要
--    **响亮地失败**(1060),静默跳过会让「列已存在但形状不对」永远补不上。
--
-- 核对:`SHOW CREATE TABLE messages\G` 里要出现 `citations json DEFAULT NULL`。
--
-- ⚠️ **两条路径的列序不同**(本机 2026-09-27 实测,纯文本差异、不影响行为):
--    · 这条 ALTER:列**追加在表末**(`… created_at, citations`);
--    · 全新库走 `create_all`:按 ORM 声明序建(`… tool_calls, citations,
--      tool_call_id, created_at`)—— 也就是新列夹在 `tool_calls` 与
--      `tool_call_id` 之间。
--    与 `db/ch08.sql` 记的那三处(索引名 / 表 COMMENT / 列 COMMENT)同类:
--    `INSERT` 列名一律显式写,**没有一条 SQL 按位置取值** —— 所以这只是形状上的
--    不一致,不是缺陷。要较真的话按 `db/ch10.sql` 的先例 `DROP TABLE` 重建。

-- 为什么会落在**这一张表**、而不是新增一张「引用表」:
--   引用是「某一条 assistant 回复的附属物」,它的生命周期与那条消息**完全一致**
--   (消息删了引用就该没),键也一样(`messages.id`)。拆表只会多一条 JOIN 与
--   一条「忘了同步删」的路。
--
-- 为什么可空(`NULL`):旧会话(这一列加出来之前写下的行)没有引用数据,
--   而「这一列没有值」与「这一轮没有引用」在**已有**的行上本来就不可区分 ——
--   用 NULL 如实表达,不让它们装成「有引用」。
--   写入方(`app/services/history.py:append_turn`)对没有引用的轮次**不写空数组**:
--   空数组与「没引用」在库里长得一样而含义不同(同表的 `tool_calls` 同理)。

ALTER TABLE messages ADD COLUMN citations JSON NULL;
